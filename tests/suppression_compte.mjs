// Suppression d'un compte : effacement s'il n'a rien saisi, retrait (nom gardé dans l'historique) sinon.
import bcrypt from 'bcryptjs';
import { handle } from '../shared/core.js';
import { memoryAdapter } from '../shared/memory-adapter.js';
import { seedReference } from '../src/demo-seed.js';
const db = memoryAdapter(seedReference());
const crypto = { hash: (p) => bcrypt.hash(p, 4), verify: (p, h) => bcrypt.compare(p, h || '') };
const call = (u, a, p) => handle(db, a, p, { userId: u, crypto, blobs: { put: async () => {}, get: async () => null } });
let ko = 0; const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) ko++; };
const err = async (p, m, re) => { try { await p; ok(false, m); } catch (e) { ok(re.test(e.message), `${m} → ${e.message}`); } };
const adm = (await call(null, 'auth.init_admin', { nom: 'Admin', prenom: 'ERP', username: 'admin', email: 'a@o.test', password: 'Admin2026!' })).user.id;
const D = (await call(adm, 'data.bootstrap')).data;
const role = (n) => D.roles.find((r) => r.nom.startsWith(n)).id;
const mk = async (u) => (await call(adm, 'user.save', { user: { nom: u, username: u, email: `${u}@o.test`, role_id: role('Responsable Commercial') }, password: 'Passe2026!' })).user.id;
const neuf = await mk('neuf'), actif = await mk('actif');
await call(actif, 'auth.change_password', { ancien: 'Passe2026!', nouveau: 'Nouveau2026!' }).catch(() => {});
const ag = D.agents?.[0] || (await call(actif, 'ref.save', { table: 'clients', row: { nom: 'Client test' } }));
await call(actif, 'ref.save', { table: 'clients', row: { nom: 'Client saisi par actif' } });
await err(call(adm, 'user.delete', { id: adm, motif: 'x' }), 'On ne supprime pas son propre compte', /propre compte/);
await err(call(adm, 'user.delete', { id: neuf }), 'Motif obligatoire', /motif/);
await err(call(actif, 'user.delete', { id: neuf, motif: 'x' }), 'Seul un gestionnaire des comptes peut supprimer', /Droit/);
let r = await call(adm, 'user.delete', { id: neuf, motif: 'Départ' });
ok(r.supprime === 'definitif', 'Compte sans aucune saisie : effacé');
r = await call(adm, 'user.delete', { id: actif, motif: 'Départ' });
ok(r.supprime === 'historique', 'Compte ayant saisi des données : retiré, nom conservé');
const U = (await call(adm, 'data.bootstrap')).data.utilisateurs;
ok(!U.some((u) => u.id === neuf), 'Compte effacé absent de la base');
const a = U.find((u) => u.id === actif);
ok(a?.statut === 'supprime' && a.nom === 'actif' && a.username !== 'actif', 'Nom gardé, identifiant libéré');
await err(call(null, 'auth.login', { identifiant: 'actif', password: 'Nouveau2026!' }), 'Le compte supprimé ne peut plus se connecter', /./);
const n = await mk('actif'); ok(!!n, 'L’identifiant libéré peut servir à un nouveau compte');
await err(call(adm, 'user.delete', { id: actif, motif: 'x' }), 'Pas de double suppression', /déjà supprimé/);
const au = (await call(adm, 'audit.list', { table: 'utilisateurs' })).rows.filter((x) => x.action === 'SUPPRESSION');
ok(au.length === 2 && au.every((x) => x.motif === 'Départ'), 'Suppressions tracées dans l’audit avec motif');
console.log(ko ? `${ko} échec(s)` : 'Tout est conforme.'); process.exit(ko ? 1 : 0);
