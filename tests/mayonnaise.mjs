// Module « Vente de mayonnaise » : fiches journalières, visites, import du classeur, objectifs, droits.
import bcrypt from 'bcryptjs';
import { readFileSync } from 'node:fs';
import { handle } from '../shared/core.js';
import { memoryAdapter } from '../shared/memory-adapter.js';
import { seedReference } from '../src/demo-seed.js';
import { today } from '../shared/logic.js';
const db = memoryAdapter(seedReference());
const crypto = { hash: (p) => bcrypt.hash(p, 4), verify: (p, h) => bcrypt.compare(p, h || '') };
const call = (u, a, p) => handle(db, a, p, { userId: u, crypto, blobs: { put: async () => {}, get: async () => null } });
let ko = 0; const ok = (c, m) => { console.log(c ? '  ✓' : '  ✗', m); if (!c) ko++; };
const err = async (p, m, re) => { try { await p; ok(false, m); } catch (e) { ok(re.test(e.message), `${m} → ${e.message}`); } };
const adm = (await call(null, 'auth.init_admin', { nom: 'Admin', prenom: 'ERP', username: 'admin', email: 'a@o.test', password: 'Admin2026!' })).user.id;
const D = (await call(adm, 'data.bootstrap')).data;
const role = (n) => D.roles.find((r) => r.nom.startsWith(n)).id;
const mk = async (u, r) => (await call(adm, 'user.save', { user: { nom: u, username: u, email: `${u}@o.test`, role_id: role(r) }, password: 'Passe2026!' })).user.id;
const rc = await mk('rc', 'Responsable Commercial'), dg = await mk('dg', 'Direction');
for (const u of [rc, dg]) await call(u, 'auth.change_password', { ancien: 'Passe2026!', nouveau: 'Nouveau2026!' });
const j = today();
const L = (p, si, vc, vk, cl) => ({ produit: p, stock_initial: si, vendu_comptant: vc, vendu_credit: vk, client_credit: cl });
let r = await call(rc, 'mayo.fiche.save', { fiche: { date: j, vendeur: 'Hamidou', axe: 'Rond-point Yantala → Koubia', observation: 'Champion partout', reaction: 'Prix Aïda jugé élevé', lignes: [L('oriba', 20, 8, 2, 'Boutique Koubia'), L('aida', 10, 3, 0), L('delice', 0, 0, 0)] } });
ok(/^MY-\d{4}-\d{5}$/.test(r.fiche.numero), `Fiche numérotée ${r.fiche.numero}`);
let B = (await call(rc, 'data.bootstrap')).data;
const lg = B.mayo_lignes.filter((l) => l.fiche_id === r.fiche.id);
ok(lg.length === 2, 'Produit sans stock ni vente ignoré');
ok(lg.find((l) => l.produit === 'oriba').prix === 9500 && lg.find((l) => l.produit === 'aida').prix === 11000, 'Prix des packs : Oriba 9 500, Aïda 11 000');
await err(call(rc, 'mayo.fiche.save', { fiche: { date: j, vendeur: 'hamidou', lignes: [L('oriba', 5, 1, 0)] } }), 'Une seule fiche par vendeur et par jour', /existe déjà/);
await err(call(rc, 'mayo.fiche.save', { fiche: { date: j, vendeur: 'Idrissa', lignes: [L('oriba', 5, 4, 2, 'X')] } }), 'Vendus > stock refusé', /stock initial/);
await err(call(rc, 'mayo.fiche.save', { fiche: { date: j, vendeur: 'Idrissa', lignes: [L('delice', 5, 0, 2)] } }), 'Client obligatoire pour un crédit', /client/);
await err(call(dg, 'mayo.fiche.save', { fiche: { date: j, vendeur: 'Idrissa', lignes: [L('delice', 5, 1, 0)] } }), 'DG en lecture seule', /Droit/);
ok((await call(dg, 'data.bootstrap')).data.mayo_fiches.length === 1, 'DG voit les fiches');
r = await call(rc, 'mayo.fiche.save', { fiche: { id: r.fiche.id, date: j, vendeur: 'Hamidou', lignes: [L('oriba', 20, 10, 2, 'Boutique Koubia')] } });
B = (await call(rc, 'data.bootstrap')).data;
ok(B.mayo_lignes.filter((l) => l.fiche_id === r.fiche.id).length === 1, 'Modification le jour même : lignes remplacées');
await err(call(rc, 'mayo.fiche.annuler', { id: r.fiche.id }), 'Motif d’annulation obligatoire', /motif/);
await call(rc, 'mayo.visite.save', { visite: { date: j, agent: 'Hamidou', client: 'Client 1', prise: 'Non', marques: 'CHAMPION / BISTRO', motif: 'Prix élevé' } });
// Import du classeur réel
const vis = JSON.parse(readFileSync(new URL('./fixtures/mayo_visites.json', import.meta.url)));
r = await call(rc, 'mayo.visites.import', { visites: vis, fichier: 'suivi.xlsx' });
ok(r.ajoutees === vis.length && !r.erreurs.length, `Import : ${r.ajoutees} visites`);
r = await call(rc, 'mayo.visites.import', { visites: vis, fichier: 'suivi.xlsx' });
ok(r.ajoutees === 0 && r.deja === vis.length, 'Réimport : rien en double');
B = (await call(rc, 'data.bootstrap')).data;
const cpt = {}; for (const v of B.mayo_visites) for (const m of v.marques) cpt[m] = (cpt[m] || 0) + 1;
ok(cpt.CHAMPION >= 40 && cpt.BISTROS >= 10 && cpt.ADELCO === 9 && !cpt.ADLECO && !cpt['STOCK CHAMPION'], `Marques normalisées : ${JSON.stringify(cpt)}`);
r = await call(rc, 'mayo.objectif.save', { mois: j.slice(0, 7), objectifs: [{ produit: 'oriba', objectif: 600 }, { produit: 'visites', objectif: 300 }] });
ok(r.objectifs.length === 2, 'Objectifs mensuels enregistrés');
await call(rc, 'mayo.objectif.save', { mois: j.slice(0, 7), objectifs: [{ produit: 'oriba', objectif: 650 }] });
B = (await call(rc, 'data.bootstrap')).data;
ok(B.mayo_objectifs.find((o) => o.produit === 'oriba').objectif === 650 && B.mayo_objectifs.length === 2, 'Objectif mis à jour sans doublon');
console.log(ko ? `${ko} échec(s)` : 'Tout est conforme.'); process.exit(ko ? 1 : 0);
