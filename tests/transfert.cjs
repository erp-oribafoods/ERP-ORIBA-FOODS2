// Transferts entre dépôts : saisie à l'écran, effet sur le tableau de bord, import par l'onglet « 6-Transferts » sans doublon
const { chromium } = require('playwright'); const fs = require('fs'); const path = require('path');
const CDN = process.env.CDN_DIR, OUT = process.env.OUT_DIR;
const XLSX = require(path.join(CDN, 'node_modules/xlsx'));
const map = { 'chart.umd.min.js': 'chart.js/dist/chart.umd.js', 'xlsx.full.min.js': 'xlsx/dist/xlsx.full.min.js', 'jspdf.umd.min.js': 'jspdf/dist/jspdf.umd.min.js', 'jspdf.plugin.autotable.min.js': 'jspdf-autotable/dist/jspdf.plugin.autotable.min.js' };
let echecs = 0; const verif = (ok, msg) => { console.log(`${ok ? '✓' : '✗'} ${msg}`); if (!ok) echecs++; };
(async () => {
  const html = '<!doctype html><html lang="fr"><head><meta charset="utf-8"></head><body>' + fs.readFileSync(path.join(__dirname, '../dist/demo.html'), 'utf8') + '</body></html>';
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true }); const errs = [];
  await ctx.route('**/*', (r) => { const u = r.request().url(); if (u.startsWith('http://erp.test/')) return r.fulfill({ contentType: 'text/html', body: html }); const f = Object.keys(map).find((k) => u.endsWith(k)); if (f) return r.fulfill({ contentType: 'application/javascript', body: fs.readFileSync(path.join(CDN, 'node_modules', map[f])) }); if (u.includes('fonts.g')) return r.fulfill({ contentType: 'text/css', body: '' }); return r.abort(); });
  const p = await ctx.newPage(); p.on('pageerror', (e) => errs.push(e.message)); p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  await p.goto('http://erp.test/'); await p.waitForSelector('#lf', { timeout: 120000 });
  await p.fill('[name=identifiant]', 'commercial'); await p.fill('[name=password]', 'Demo2026'); await p.click('#lf button[type=submit]'); await p.waitForSelector('.layout');
  const D = () => p.evaluate(() => window.__ERP_DEBUG__());
  const dep = (await D()).agents.filter((a) => a.role_circuit === 'depot').sort((a, b) => a.nom.localeCompare(b.nom, 'fr'));
  const [A, B] = [dep[0], dep[1]];
  const tableau = async () => {
    await p.keyboard.press('Escape').catch(() => {}); await p.waitForTimeout(200); await p.evaluate(() => { location.hash = 'accueil'; }); await p.waitForTimeout(500);
    await p.click('[data-per="jour"]'); await p.fill('#e-date', new Date().toISOString().slice(0, 10)); await p.dispatchEvent('#e-date', 'change'); await p.waitForTimeout(2200);
    const th = await p.$$eval('#et thead th', (t) => t.map((x) => x.textContent.trim()));
    const rows = await p.$$eval('#et tbody tr', (rs) => rs.map((r) => [...r.children].map((c) => c.innerText.trim())));
    const col = (l) => th.findIndex((x) => x.startsWith(l));
    const n = (s) => Number(String(s).replace(/[^\d,−-]/g, '').replace('−', '-').replace(',', '.')) || 0;
    const ligne = (nom) => { const r = rows.find((x) => x[0] === nom); return { recuT: n(r[col('Reçu d’un dépôt')]), transf: Math.abs(n(r[col('Transféré')])), fin: n(r[col('Stock fin')]) }; };
    return { th, a: ligne(A.nom), b: ligne(B.nom) };
  };
  const t0 = await tableau();
  verif(t0.th.includes('Reçu d’un dépôt') && t0.th.some((x) => x.startsWith('Transféré')), `Colonnes du tableau de bord : ${t0.th.join(' | ')}`);
  // Saisie à l'écran depuis la page Dépôts
  await p.evaluate(() => { location.hash = 'depots'; }); await p.waitForTimeout(500);
  await p.click(`[data-d="${A.id}"]`); await p.waitForTimeout(400);
  await p.click('#d-transf'); await p.waitForSelector('.modal [name=depot_dest_id]');
  const choix = await p.$$eval('.modal [name=depot_dest_id] option', (o) => o.map((x) => x.value));
  verif(!choix.includes(A.id) && choix.includes(B.id), `Le dépôt qui envoie (${A.nom}) n’est pas proposé comme destination`);
  await p.selectOption('.modal [name=depot_dest_id]', B.id); await p.selectOption('.modal [name=produit_id]', { index: 1 }); await p.fill('.modal [name=cartons]', '10');
  await p.screenshot({ path: path.join(OUT, 'transfert-form.png') });
  await p.click('#ms'); await p.waitForTimeout(800);
  verif(!(await p.$('.modal [name=depot_dest_id]')), `Transfert enregistré : ${A.nom} → ${B.nom}, 10 cartons`);
  const t1 = await tableau();
  await p.screenshot({ path: path.join(OUT, 'transfert-tableau.png'), fullPage: true });
  verif(t1.a.transf - t0.a.transf === 10 && t1.b.recuT - t0.b.recuT === 10, `Tableau de bord : ${A.nom} transféré +10, ${B.nom} reçu d’un dépôt +10`);
  verif(t0.a.fin - t1.a.fin === 10 && t1.b.fin - t0.b.fin === 10, `Stock fin : ${A.nom} ${t0.a.fin} → ${t1.a.fin}, ${B.nom} ${t0.b.fin} → ${t1.b.fin}`);
  // Import : onglet 6-Transferts du modèle
  await p.evaluate(() => { location.hash = 'saisie-rapide'; }); await p.waitForTimeout(500);
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('#f-circ-mod')]);
  const fm = path.join(OUT, 'modele_transfert.xlsx'); await dl.saveAs(fm);
  const wb = XLSX.readFile(fm);
  verif(wb.SheetNames.includes('6-Transferts'), `Modèle : onglet 6-Transferts présent (${wb.SheetNames.join(', ')})`);
  const ws = wb.Sheets['6-Transferts']; const aoa = XLSX.utils.sheet_to_json(ws, { header: 1, defval: '' });
  const prod = (await D()).produits.find((x) => x.actif !== false).nom;
  const j = new Date().toISOString().slice(0, 10).split('-').reverse().join('/');
  aoa.push([j, B.code, A.code, prod, 4, 'retour']);
  wb.Sheets['6-Transferts'] = XLSX.utils.aoa_to_sheet(aoa); const f2 = path.join(OUT, 'modele_transfert_rempli.xlsx'); XLSX.writeFile(wb, f2);
  const imp = async () => {
    await p.keyboard.press('Escape').catch(() => {}); await p.evaluate(() => { location.hash = 'saisie-rapide'; }); await p.waitForTimeout(500);
    await p.click('#f-circ'); await p.waitForSelector('.modal [data-f]', { state: 'attached' });
    await p.setInputFiles('.modal [data-f]', f2); await p.waitForSelector('.modal [data-b] table', { timeout: 60000 }); await p.waitForTimeout(300);
    return p.$$eval('.modal [data-b] tbody tr', (rs) => rs.map((r) => [...r.children].map((c) => c.textContent.trim())));
  };
  let t = await imp(); const lt = t.find((r) => /Transferts/.test(r[0]));
  verif(lt && lt[1] === '1' && lt[3] === '0', `Contrôle de l’import : ${lt?.join(' / ')}`);
  await p.click('.modal [data-go]'); await p.waitForSelector('.modal .note.ok', { timeout: 60000 });
  console.log('  ', (await p.textContent('.modal .note.ok')).replace(/\s+/g, ' ').slice(0, 200));
  const nb = (await D()).circuit_mvts.filter((m) => m.type === 'transfert' && m.statut !== 'annule').length;
  verif(nb === 2, `Transferts enregistrés : ${nb}`);
  t = await imp(); const lt2 = t.find((r) => /Transferts/.test(r[0]));
  verif(lt2 && lt2[1] === '0' && lt2[2] === '1', `Même fichier réimporté : ${lt2?.join(' / ')} (rien de nouveau)`);
  const t2 = await tableau();
  verif(t2.a.recuT - t1.a.recuT === 4 && t2.b.transf - t1.b.transf === 4, `Après import : ${B.nom} → ${A.nom} 4 cartons pris en compte`);
  verif(!errs.length, errs.length ? 'Erreurs : ' + errs.slice(0, 3).join(' | ') : 'Aucune erreur dans la page');
  await b.close();
  console.log(echecs ? `${echecs} échec(s)` : 'Tous les contrôles sont réussis');
  process.exit(echecs ? 1 : 0);
})();
